// Le icone del gioco, disegnate a pixel come in un videogioco anni '90 (e come le stampa un fax): "#" e' un
// pixel pieno, "+" un pixel a meta' (il grigio del fax, l'ombra), "." vuoto. Diventano SVG nitidi a ogni misura
// e prendono il colore del testo attorno.

export function pixel(righe, classe = "") {
  const h = righe.length, w = righe[0].length;
  const tracce = { "#": "", "+": "" };
  righe.forEach((r, y) => {
    for (let x = 0; x < w;) {
      const c = r[x];
      if (!(c in tracce)) { x++; continue; }
      let l = 1;
      while (r[x + l] === c) l++;
      tracce[c] += `M${x} ${y}h${l}v1h-${l}z`;
      x += l;
    }
  });
  return `<svg class="pix ${classe}" viewBox="0 0 ${w} ${h}" aria-hidden="true" focusable="false" shape-rendering="crispEdges">`
    + (tracce["+"] ? `<path d="${tracce["+"]}" fill="currentColor" opacity="0.42"/>` : "")
    + `<path d="${tracce["#"]}" fill="currentColor"/></svg>`;
}

